// Охота на небоевую дичь (кнопка «🏹 Охота» во вкладке «Кузнечное дело»).
// Дичь — только безобидные звери, которых можно встретить в диких местах владения: кролики, олени, лоси, лисы, козы.
// Хищники и враждебные звери (волки, медведи, саблезубы, хоркеры…) сюда не входят — с ними разговор в бою.
// Добыча (мясо / шкура / рога) соответствует таблицам добычи в enemies-data.js («Животные»); предметы берутся из items-data.js.
//
// HOLD_FAUNA — вес появления зверя в каждом владении (по тексту «Фауна» справочника владений и вики UESP).
// REGION_MOD — множители веса по региону, который задал мастер (горы — козы, лес — олени и т.д.).
// Подземелье — дичи нет вовсе. Шанс вернуться ни с чем — HUNT_FAIL_CHANCE (как на рыбалке, 20%).
(function () {
    const HUNT_FAIL_CHANCE = 0.2;

    // drops: { item, min, max, chance } — chance по умолчанию 1
    const ANIMALS = {
        'Кролик': { drops: [{ item: 'Сырая кроличья ножка', min: 1, max: 2 }] },
        'Олень (самка)': { drops: [{ item: 'Оленина', min: 1, max: 2 }, { item: 'Оленья шкура', min: 1, max: 1 }, { item: 'Маленькие рога', min: 1, max: 1, chance: 0.5 }] },
        'Олень (самец)': { drops: [{ item: 'Оленина', min: 1, max: 2 }, { item: 'Оленья шкура', min: 1, max: 1 }, { item: 'Большие рога', min: 1, max: 1, chance: 0.5 }] },
        'Лось': { drops: [{ item: 'Оленина', min: 2, max: 3 }, { item: 'Оленья шкура', min: 1, max: 1 }, { item: 'Большие рога', min: 1, max: 1, chance: 0.5 }] },
        'Лиса': { drops: [{ item: 'Шкура лисицы', min: 1, max: 1 }] },
        'Снежная лиса': { drops: [{ item: 'Шкура снежной лисицы', min: 1, max: 1 }] },
        'Коза': { drops: [{ item: 'Козья шкура', min: 1, max: 1 }, { item: 'Козий окорок', min: 1, max: 1 }, { item: 'Козьи рога', min: 1, max: 1, chance: 0.5 }] }
    };

    const DEFAULT_FAUNA = { 'Кролик': 6, 'Олень (самка)': 3, 'Олень (самец)': 3, 'Лиса': 3, 'Коза': 3 };
    const HOLD_FAUNA = {
        'Вайтран': { 'Кролик': 6, 'Олень (самка)': 4, 'Олень (самец)': 3, 'Лось': 2, 'Лиса': 3, 'Коза': 3 },
        'Винтерхолд': { 'Кролик': 5, 'Олень (самка)': 3, 'Олень (самец)': 3, 'Лиса': 2, 'Снежная лиса': 4, 'Коза': 5 },
        'Рифт': { 'Кролик': 6, 'Олень (самка)': 4, 'Олень (самец)': 4, 'Лиса': 3, 'Коза': 4 },
        'Фолкрит': { 'Кролик': 6, 'Олень (самка)': 8, 'Олень (самец)': 6, 'Лось': 2, 'Лиса': 3, 'Коза': 3 }, // как в Вайтране, но оленей заметно больше
        'Солитьюд (Хаафингар)': { 'Кролик': 6, 'Олень (самка)': 4, 'Олень (самец)': 3, 'Лось': 2, 'Лиса': 3, 'Снежная лиса': 3, 'Коза': 4 }, // равнины как в Вайтране + заснеженные горы как в Белом береге
        'Хьялмарк (Морфал)': { 'Кролик': 3, 'Олень (самка)': 3, 'Олень (самец)': 3, 'Лиса': 2, 'Коза': 3 }, // вики: на юге олени и козы
        'Истмарк (Виндхельм)': { 'Кролик': 5, 'Олень (самка)': 4, 'Олень (самец)': 4, 'Лиса': 2, 'Снежная лиса': 2, 'Коза': 5 }, // вики: у серных источников олени, кролики, козы
        'Белый берег (Данстар)': { 'Кролик': 4, 'Олень (самка)': 3, 'Олень (самец)': 2, 'Лиса': 2, 'Снежная лиса': 3, 'Коза': 4 },
        'Маркарт (Предел)': { 'Кролик': 6, 'Лось': 2, 'Лиса': 3, 'Коза': 3 }, // как в Вайтране, но без оленей
        'Схолстейм': { 'Кролик': 5, 'Олень (самка)': 4, 'Олень (самец)': 4, 'Лось': 4 } // вики: на острове олени, лоси, кролики
    };
    const REGION_MOD = {
        'Лес': { 'Олень (самка)': 1.5, 'Олень (самец)': 1.5, 'Лось': 1.5, 'Лиса': 1.5 },
        'Равнина': { 'Кролик': 1.5, 'Олень (самка)': 1.2, 'Олень (самец)': 1.2 },
        'Горы': { 'Коза': 2, 'Снежная лиса': 1.5, 'Кролик': 0.5, 'Олень (самка)': 0.6, 'Олень (самец)': 0.6, 'Лось': 0.5 },
        'Болото': { 'Кролик': 0.8, 'Олень (самка)': 0.5, 'Олень (самец)': 0.5, 'Лось': 0.5, 'Коза': 0.4, 'Лиса': 0.8 },
        'Побережье': { 'Кролик': 0.7, 'Олень (самка)': 0.5, 'Олень (самец)': 0.5, 'Лось': 0.5, 'Коза': 0.7 }
    };

    // Ключ владения из справочника: точное совпадение, иначе по вхождению (мастер мог выбрать сокращённое название)
    function resolveHuntHold(hold) {
        if (!hold) return null;
        if (HOLD_FAUNA[hold]) return hold;
        return Object.keys(HOLD_FAUNA).find(h => h.indexOf(hold) !== -1 || hold.indexOf(h) !== -1) || null;
    }

    // Список { name, weight } для владения и региона. Подземелье — пусто.
    function getHuntingPool(hold, region) {
        if (region === 'Подземелье') return [];
        const key = resolveHuntHold(hold);
        const base = key ? HOLD_FAUNA[key] : DEFAULT_FAUNA;
        const mod = (region && REGION_MOD[region]) || {};
        return Object.keys(base).map(n => ({ name: n, weight: base[n] * (mod[n] || 1) })).filter(p => p.weight > 0);
    }

    // rnd — функция 0..1 (для тестов). Возвращает { nothing:true } или { animal, drops:[{name,qty}] }
    function rollHunt(hold, region, rnd) {
        rnd = rnd || Math.random;
        const pool = getHuntingPool(hold, region);
        if (!pool.length || rnd() < HUNT_FAIL_CHANCE) return { nothing: true, noGame: !pool.length };
        const total = pool.reduce((s, p) => s + p.weight, 0);
        let r = rnd() * total, pick = pool[0];
        for (const p of pool) { r -= p.weight; if (r <= 0) { pick = p; break; } }
        const drops = [];
        ANIMALS[pick.name].drops.forEach(d => {
            if (d.chance !== undefined && rnd() >= d.chance) return;
            drops.push({ name: d.item, qty: d.min + Math.floor(rnd() * (d.max - d.min + 1)) });
        });
        return { animal: pick.name, drops };
    }

    window.huntData = { animals: ANIMALS, holdFauna: HOLD_FAUNA, regionMod: REGION_MOD, defaultFauna: DEFAULT_FAUNA, failChance: HUNT_FAIL_CHANCE };
    window.getHuntingPool = getHuntingPool;
    window.rollHunt = rollHunt;
    window.resolveHuntHold = resolveHuntHold;
})();
